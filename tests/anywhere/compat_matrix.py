#!/usr/bin/env python3
"""Generate the Anywhere compatibility matrix FROM GATE EVIDENCE (M6).

    compat_matrix.py --context CONTEXT.txt EVIDENCE.json... > docs/anywhere-compatibility.md

Inputs are the JSON results the VM gates write (e2e_convert.py summaries,
test_preflight_refusals.py results) and the evidence run's context.txt
naming the commit. A combination appears as supported only if a gate
converted it; nothing is listed from intent. Every row names its source.
"""

import argparse
import json
import sys
from pathlib import Path


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--context", required=True)
    p.add_argument("evidence", nargs="+")
    a = p.parse_args()
    ctx = dict(line.split("=", 1) for line in Path(a.context).read_text().splitlines() if "=" in line)
    converted, refused = [], []
    for f in a.evidence:
        doc = json.loads(Path(f).read_text())
        if isinstance(doc, dict) and "passed" in doc:
            for r in doc["passed"]:
                converted.append((r, Path(f).name))
        elif isinstance(doc, dict):
            for case, r in doc.items():
                if isinstance(r, dict) and "check" in r:
                    refused.append((case, r, Path(f).name))
    out = ["# ReproOS Anywhere compatibility (generated from gate evidence)", "",
           f"Generated by `tests/anywhere/compat_matrix.py` from the gate results of the evidence run "
           f"at reproos `{ctx.get('reproos', '?')[:12]}` (reprobuild `{ctx.get('reprobuild', '?').split()[0][:12]}`, "
           f"host `{ctx.get('host', '?').split()[0]}`). Do not edit by hand: rerun the gates and regenerate.", "",
           "**Every conversion below installed the FIXTURE payload** (`conversion_qualified: false`): this "
           "matrix qualifies the conversion PROTOCOL on these source systems, not a ReproOS release.", "",
           "## Converted end to end", "",
           "| Source | Image | Arch | Firmware | Disk controller | Network | Takeover | Planning environment | Invocation | Apply (s) | Evidence |",
           "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r, src in sorted(converted, key=lambda x: (x[0]["distro"], x[0].get("controller", ""),
                                                    x[0].get("invocation", ""))):
        out.append(f"| {r['distro']} | `{r.get('image') or '?'}` | {r.get('architecture', 'x86_64')} | "
                   f"{r.get('firmware', 'uefi')} | {r.get('controller', 'virtio-blk')} | {r.get('network', 'dhcp')} | "
                   f"{r.get('takeover', '?')} | {r.get('planning_environment') or '?'} | "
                   f"{r.get('invocation', 'preflight/plan/apply')} | {r['apply_seconds']} | `{src}` |")
    out += ["", "## Refused before any write", "",
            "| Shape | Blocking check | Reason | Evidence |", "|---|---|---|---|"]
    for case, r, src in sorted(refused):
        out.append(f"| {case} | `{r['check']}` | {r['detail']} | `{src}` |")
    out += ["", "## Not supported", "",
            "Converting to aarch64 (ReproOS is built for x86_64 only); legacy-BIOS installation; static "
            "management networks; Secure Boot; LVM, RAID or encrypted targets; provider rescue planes "
            "other than the QEMU test supervisor; any combination not listed above. A shape in the "
            "refusal table is refused by a gate-proven check; the rest are not covered by any gate.", ""]
    sys.stdout.write("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
