static QString parseTomlString(QString value) {
    value = value.trimmed();
    if (value.size() >= 2 && value.startsWith('"') && value.endsWith('"')) {
        value = value.mid(1, value.size() - 2);
        value.replace("\\n", "\n");
        value.replace("\\\"", "\"");
        value.replace("\\\\", "\\");
    }
    return value;
}

static QStringList parseTomlArray(QString value) {
    value = value.trimmed();
    if (value.startsWith('[') && value.endsWith(']'))
        value = value.mid(1, value.size() - 2);
    QStringList result;
    for (const QString &entry : value.split(',', Qt::SkipEmptyParts))
        result.append(parseTomlString(entry));
    return result;
}

static bool parseTomlBool(const QString &value, bool *parsed) {
    if (value == "true") {
        *parsed = true;
        return true;
    }
    if (value == "false") {
        *parsed = false;
        return true;
    }
    return false;
}

bool InstallerState::loadAutoConfig(const QString &configPath,
                                    QString *error) {
    QFile file(configPath);
    if (!file.open(QIODevice::ReadOnly | QIODevice::Text)) {
        if (error)
            *error = QString("cannot open %1: %2")
                .arg(configPath, file.errorString());
        return false;
    }

    QString section;
    int lineNumber = 0;
    QTextStream input(&file);
    while (!input.atEnd()) {
        QString line = input.readLine().trimmed();
        ++lineNumber;
        if (line.isEmpty() || line.startsWith('#'))
            continue;
        if (line.startsWith('[') && line.endsWith(']')) {
            section = line.mid(1, line.size() - 2).trimmed();
            continue;
        }
        const int equals = line.indexOf('=');
        if (equals < 1) {
            if (error)
                *error = QString("invalid TOML assignment at line %1")
                    .arg(lineNumber);
            return false;
        }
        const QString key = line.left(equals).trimmed();
        const QString rawValue = line.mid(equals + 1).trimmed();
        const QString qualified = section.isEmpty()
            ? key : section + '.' + key;
        const QString value = parseTomlString(rawValue);

        bool handled = true;
        if (qualified == "schema_version") {
            bool ok = false;
            const int version = value.toInt(&ok);
            if (!ok || (version != 1 && version != 2)) {
                if (error)
                    *error = "unsupported schema_version: " + value;
                return false;
            }
            m_schemaVersion = version;
        } else if (qualified == "hostname") {
            setHostname(value);
        } else if (qualified == "regional.locale") {
            setLocale(value);
        } else if (qualified == "regional.timezone") {
            setTimezone(value);
        } else if (qualified == "regional.keymap") {
            setKeymap(value);
        } else if (qualified == "user.name") {
            setUsername(value);
        } else if (qualified == "user.full_name") {
            setFullName(value);
        } else if (qualified == "user.password_hash") {
            m_password.clear();
            m_passwordHash = value;
            emit passwordChanged();
        } else if (qualified == "user.locked") {
            if (!parseTomlBool(value, &m_userLocked)) {
                if (error)
                    *error = "user.locked must be a boolean";
                return false;
            }
        } else if (qualified == "user.groups") {
            setIsAdmin(parseTomlArray(rawValue).contains("wheel"));
        } else if (qualified == "user.shell") {
            m_userShell = value;
        } else if (qualified == "sudo.policy") {
            m_sudoPolicy = value;
        } else if (qualified == "sudo.users") {
            m_sudoUsers = parseTomlArray(rawValue);
        } else if (qualified == "disk.size_gb") {
            bool ok = false;
            const int parsed = value.toInt(&ok);
            if (!ok || parsed < 4) {
                if (error)
                    *error = "disk.size_gb must be an integer of at least 4";
                return false;
            }
            m_diskSizeGb = parsed;
        } else if (qualified == "disk.layout.type") {
            if (value != "uefi-ext4") {
                if (error)
                    *error = "only disk.layout.type=uefi-ext4 is supported";
                return false;
            }
            setDiskoPreset("simple");
        } else if (qualified == "disk.layout.esp_size_mib") {
            bool ok = false;
            const int parsed = value.toInt(&ok);
            if (!ok || parsed < 128) {
                if (error)
                    *error = "disk.layout.esp_size_mib must be at least 128";
                return false;
            }
            m_espSizeMib = parsed;
        } else if (qualified == "de.default") {
            if (value != "sway") {
                if (error)
                    *error = "this image supports only de.default=sway";
                return false;
            }
            setDesktopKind(value);
        } else if (qualified == "network.ipv4") {
            if (value != "dhcp") {
                if (error)
                    *error = "this image supports only network.ipv4=dhcp";
                return false;
            }
            m_networkIpv4 = value;
        } else if (qualified == "ssh.enabled") {
            if (!parseTomlBool(value, &m_sshEnabled)) {
                if (error) *error = "ssh.enabled must be a boolean";
                return false;
            }
        } else if (qualified == "ssh.permit_root_login") {
            if (!parseTomlBool(value, &m_sshPermitRootLogin)) {
                if (error) *error = "ssh.permit_root_login must be a boolean";
                return false;
            }
        } else if (qualified == "ssh.password_authentication") {
            if (!parseTomlBool(value, &m_sshPasswordAuthentication)) {
                if (error) *error = "ssh.password_authentication must be a boolean";
                return false;
            }
        } else if (qualified == "ssh.authorized_keys_source") {
            m_sshAuthorizedKeysSource = value;
        } else if (qualified == "firewall.default_policy") {
            m_firewallDefaultPolicy = value;
        } else if (qualified == "firewall.allowed_tcp_ports") {
            m_firewallAllowedTcpPorts = parseTomlArray(rawValue);
        } else if (qualified == "firewall.ssh_source_cidrs") {
            m_firewallSshSourceCidrs = parseTomlArray(rawValue);
        } else if (qualified == "first_boot.enrollment") {
            m_firstBootEnrollment = value;
        } else if (qualified == "first_boot.enrollment_label") {
            m_firstBootEnrollmentLabel = value;
        } else if (qualified == "activities.enabled") {
            const QStringList activities = parseTomlArray(rawValue);
            if (!activities.isEmpty()) {
                if (error)
                    *error = "activity modules are not available in this image";
                return false;
            }
            setActiveActivities(activities);
        } else if (qualified == "install.target_device") {
            setTargetDevice(value);
        } else {
            handled = false;
        }

        if (!handled) {
            if (error)
                *error = QString("unknown configuration key at line %1: %2")
                    .arg(lineNumber).arg(qualified);
            return false;
        }
    }

    if (m_hostname.isEmpty() || m_username.isEmpty()) {
        if (error)
            *error = "hostname and user.name must not be empty";
        return false;
    }
    if (m_schemaVersion == 1) {
        if (!m_passwordHash.startsWith("$6$")) {
            if (error)
                *error = "user.password_hash must be a SHA-512 crypt hash";
            return false;
        }
    } else {
        if (!m_userLocked || !m_passwordHash.isEmpty()) {
            if (error)
                *error = "schema v2 reusable profiles require user.locked=true and no password_hash";
            return false;
        }
        if (m_sudoPolicy != "passwordless" || !m_sudoUsers.contains(m_username)) {
            if (error)
                *error = "schema v2 requires passwordless sudo for the configured user";
            return false;
        }
        if (!m_sshEnabled || m_sshPermitRootLogin ||
            m_sshPasswordAuthentication ||
            m_sshAuthorizedKeysSource != "instance-enrollment") {
            if (error)
                *error = "schema v2 requires key-only SSH through instance enrollment";
            return false;
        }
        if (m_firewallDefaultPolicy != "deny" ||
            !m_firewallAllowedTcpPorts.contains("22") ||
            m_firewallSshSourceCidrs.isEmpty()) {
            if (error)
                *error = "schema v2 requires deny-by-default firewall rules bounded for SSH";
            return false;
        }
        if (m_firewallSshSourceCidrs.contains("0.0.0.0/0") ||
            m_firewallSshSourceCidrs.contains("::/0")) {
            if (error)
                *error = "schema v2 forbids unbounded SSH source networks";
            return false;
        }
        if (m_firstBootEnrollment != "required" ||
            m_firstBootEnrollmentLabel.isEmpty()) {
            if (error)
                *error = "schema v2 requires first-boot enrollment";
            return false;
        }
    }
    if (m_targetDevice.isEmpty())
        setTargetDevice("/dev/vda");
    setWipeAcknowledged(true);
    return true;
}

bool InstallerState::writeConfigurationArtifacts(const QString &directory,
                                                  QString *error) {
    const QString autoConfig = renderAutoConfigToml();
    if (autoConfig.isEmpty()) {
        if (error)
            *error = "cannot render auto-config.toml";
        return false;
    }
    if (!QDir().mkpath(directory)) {
        if (error)
            *error = "cannot create artifact directory: " + directory;
        return false;
    }

    const QList<QPair<QString, QString>> artifacts = {
        {"auto-config.toml", autoConfig},
        {"system.nim", renderSystemNim()},
        {"hardware.nim", renderDiskoNim()},
        {"disko.json", renderDiskoJson()},
        {"home.nim", renderHomeNim()}
    };
    for (const auto &artifact : artifacts) {
        const QString path = QDir(directory).filePath(artifact.first);
        if (!writeFileAtomic(path, artifact.second, error)) {
            return false;
        }
    }
    return true;
}

// M9.R.23.2 -- render the M9.R.22 disko block matching the chosen
// preset. The "advanced" preset produces a hardware "<id>": block with
// no disko: sub-block + a comment instructing the user to add one
// post-install.
QString InstallerState::renderDiskoNim(const QString &id) const {
    QString out;
    QTextStream s(&out);
    s << "# /etc/repro/hardware.nim --- generated by the ReproOS installer\n";
    s << "import repro_profile\n\n";
    s << "hardware \"" << id << "\":\n";
    s << "  cpu:\n";
    s << "    arch: \"x86_64\"\n";
    s << "    microcode: \"intel\"\n";
    s << "  boot:\n";
    s << "    loaderDevice: \"" << (m_targetDevice.isEmpty()
        ? QStringLiteral("/dev/vda") : m_targetDevice) << "\"\n";

    if (m_diskoPreset == "advanced") {
        s << "  # disko: block omitted -- the user opted for the\n";
        s << "  # advanced layout. Hand-author the disks/pools blocks\n";
        s << "  # via the M9.R.22 macro vocabulary; see\n";
        s << "  # reprobuild-specs/ReproOS-Disko-Port.md for examples.\n";
        return out;
    }

    const QString dev = m_targetDevice.isEmpty()
        ? QStringLiteral("/dev/vda") : m_targetDevice;

    s << "  disko:\n";
    s << "    disks:\n";
    s << "      \"main\":\n";
    s << "        device: \"" << dev << "\"\n";
    s << "        table: gpt\n";
    s << "        partitions:\n";
    s << "          \"esp\":\n";
    s << "            kind: esp\n";
    s << "            size: \"" << m_espSizeMib << "M\"\n";
    s << "            bootable: true\n";
    s << "            content:\n";
    s << "              filesystem:\n";
    s << "                format: \"vfat\"\n";
    s << "                mountpoint: \"/boot\"\n";
    s << "          \"root\":\n";
    s << "            kind: linux\n";
    s << "            size: \"100%\"\n";
    s << "            content:\n";

    if (m_diskoPreset == "encrypted") {
        // LUKS2 + btrfs subvols. The keyFile = "interactive" signals
        // the M9.R.22b apply driver to consume the passphrase from the
        // CT_DISK_PASSPHRASE env var instead of a key file.
        s << "              encrypted:\n";
        s << "                encryption:\n";
        s << "                  kind: \"luks2\"\n";
        s << "                  keyFile: \"interactive\"\n";
        s << "                  allowDiscards: true\n";
        s << "                inner:\n";
        s << "                  filesystem:\n";
        s << "                    format: \"btrfs\"\n";
        s << "                    mountpoint: \"/\"\n";
        s << "                    subvols:\n";
        s << "                      \"@\":\n";
        s << "                        path: \"/\"\n";
        s << "                      \"@home\":\n";
        s << "                        path: \"/home\"\n";
        s << "                      \"@nix\":\n";
        s << "                        path: \"/nix\"\n";
    } else {
        // simple preset (default): ext4 root.
        s << "              filesystem:\n";
        s << "                format: \"ext4\"\n";
        s << "                mountpoint: \"/\"\n";
        s << "                mountOptions: @[\"noatime\"]\n";
    }
    return out;
}

// M9.R.24.2 -- renderDiskoJson: pre-compute the SystemHardwareSpec
// JSON the disk_apply driver consumes, so the live ISO's installer
// can `repro disk apply --confirm <disko.json>` WITHOUT a Nim
// toolchain (the .nim path goes through `nim r` -- requires nim +
// gcc + libc-dev in the live filesystem, which we deliberately don't
// ship). The output must match libs/repro_profile/.../emit.nim's
// emitSystemHardwareJson for the same SystemHardwareSpec input.
//
// Currently supports the `simple` preset only; encrypted/advanced
// fall through to the .nim path (which still requires Nim).
QString InstallerState::renderDiskoJson(const QString &id) const {
    QString out;
    QTextStream s(&out);
    auto esc = [](const QString &x) {
        QString r;
        for (QChar c : x) {
            if (c == '"' || c == '\\') r += '\\';
            r += c;
        }
        return r;
    };
    const QString dev = m_targetDevice.isEmpty()
        ? QStringLiteral("/dev/vda") : m_targetDevice;
    // Filesystem content node (filesystem kind) -- includes all keys
    // parseContentSpec requires when kind==filesystem.
    auto fsContent = [&](const QString &format, const QString &mountpoint,
                         const QString &mountOpts) {
        QString r;
        r += "{\"kind\":\"filesystem\"";
        r += ",\"format\":\"" + esc(format) + "\"";
        r += ",\"mountpoint\":\"" + esc(mountpoint) + "\"";
        r += ",\"mountOptions\":" + mountOpts;
        r += ",\"label\":\"\"";
        r += ",\"subvols\":[]";
        r += "}";
        return r;
    };
    s << "{";
    s << "\"id\":\"" << esc(id) << "\"";
    s << ",\"cpuArch\":\"x86_64\"";
    s << ",\"cpuMicrocode\":\"intel\"";
    s << ",\"kernelModules\":[]";
    s << ",\"loaderDevice\":\"" << esc(dev) << "\"";
    s << ",\"filesystems\":[]";
    s << ",\"graphicsDrivers\":[]";
    s << ",\"audioCards\":[]";
    if (m_diskoPreset == "simple" || m_diskoPreset.isEmpty()) {
        s << ",\"disko\":{";
        s << "\"disks\":{";
        s << "\"main\":{";
        s << "\"device\":\"" << esc(dev) << "\"";
        s << ",\"type\":\"gpt\"";
        s << ",\"partitions\":{";
        // ESP partition.
        s << "\"esp\":{";
        s << "\"type\":\"esp\"";
        s << ",\"size\":\"" << m_espSizeMib << "M\"";
        s << ",\"bootable\":true";
        s << ",\"content\":" << fsContent("vfat", "/boot", "[]");
        s << "},";
        // Root partition.
        s << "\"root\":{";
        s << "\"type\":\"linux\"";
        s << ",\"size\":\"100%\"";
        s << ",\"bootable\":false";
        s << ",\"content\":" << fsContent("ext4", "/", "[\"noatime\"]");
        s << "}";
        s << "}";
        s << "}";
        s << "}";
        s << ",\"pools\":[]";
        s << "}";
    }
    s << "}\n";
    return out;
}

// ---------------------------------------------------------------------
// M9.R.23.2 -- lsblk-driven disk refresh.
// ---------------------------------------------------------------------

void InstallerState::refreshAvailableDisks() {
    QStringList disks;
#ifdef Q_OS_LINUX
    QProcess p;
    // -d: skip partitions/holders, -n: no header, -o: chosen columns,
    // -p: print full /dev/* path (we then strip the prefix for the
    // model so the QML side has both forms).
    p.start("lsblk", {"-d", "-n", "-o", "NAME,SIZE,MODEL,VENDOR"});
    if (!p.waitForStarted(2000)) {
        // lsblk missing -- fall back to a single placeholder so the QML
        // doesn't render an empty combo + the user can still see the
        // wizard works end-to-end on test hosts without util-linux.
        disks << "vda 16G QEMU";
        setAvailableDisks(disks);
        return;
    }
    p.waitForFinished(5000);
    const QString out = QString::fromUtf8(p.readAllStandardOutput());
    for (const QString &lineRaw : out.split('\n')) {
        const QString line = lineRaw.trimmed();
        if (line.isEmpty()) continue;
        // Filter loopback + ram devices; users don't want to install
        // onto loop0 or zram by accident.
        if (line.startsWith("loop") || line.startsWith("ram") ||
            line.startsWith("zram") || line.startsWith("sr"))
            continue;
        disks << line;
    }
#else
    // Non-Linux host (the Windows build of the installer is dev-only;
    // PRD Sec 7.1 pins the runtime to the live ISO + Wayland). Emit a
    // placeholder so the QML still works for screenshots.
    disks << "sda 100G Virtual";
    disks << "sdb 500G Virtual";
#endif
    setAvailableDisks(disks);
}

