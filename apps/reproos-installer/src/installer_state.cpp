void InstallerState::appendLog(const QString &line) {
    const QString stamp = QDateTime::currentDateTimeUtc()
        .toString("yyyy-MM-dd hh:mm:ss");
    const QString stamped = "[" + stamp + "] " + line;
    m_installLog += stamped + "\n";
    emit installLogChanged();
    // M9.R.23.5 -- when running headless (no QML engine, e.g. via
    // --automated CONFIG_TOML or any caller that didn't bind a Qml
    // engine to installerState), mirror the line to stderr so the
    // operator sees the same trace the GUI would show. The GUI path
    // ignores this duplicate; QML binds to installLogChanged and
    // re-reads installLog every time.
    QTextStream(stderr) << stamped << '\n';
}

void InstallerState::setInstallStatus(const QString &s) {
    if (m_installStatus == s) return;
    m_installStatus = s;
    emit installStatusChanged();
}

void InstallerState::setInstallProgress(qreal v) {
    if (qFuzzyCompare(m_installProgress, v)) return;
    m_installProgress = v;
    emit installProgressChanged();
}

void InstallerState::setInstallRunning(bool v) {
    if (m_installRunning == v) return;
    m_installRunning = v;
    emit installRunningChanged();
}

bool InstallerState::dryRunDestructive() const {
    const QByteArray v =
        qgetenv("REPRO_DISK_DRY_RUN");
    return m_dryRun || (!v.isEmpty() && v != "0");
}

// Locate the `repro` binary. The live ISO ships it at /usr/bin/repro;
// during dev we honour CT_REPRO_BINARY for an override path.
static QString reproBinary() {
    const QByteArray env = qgetenv("CT_REPRO_BINARY");
    if (!env.isEmpty()) return QString::fromUtf8(env);
    if (QFileInfo::exists("/usr/bin/repro")) return "/usr/bin/repro";
    // Fall back to PATH lookup -- QProcess does this automatically when
    // the program string has no directory separator.
    return "repro";
}

int InstallerState::runReproSubcommand(const QStringList &args,
                                        int timeoutMs) {
    QProcess p;
    p.setProcessChannelMode(QProcess::MergedChannels);
    const QString bin = reproBinary();
    appendLog(QString("$ %1 %2").arg(bin, args.join(' ')));
    p.start(bin, args);
    if (!p.waitForStarted(5000)) {
        appendLog(QString("spawn failed: %1").arg(p.errorString()));
        return -1;
    }
    if (!p.waitForFinished(timeoutMs)) {
        p.kill();
        appendLog(QString("timeout after %1ms").arg(timeoutMs));
        return -2;
    }
    const QString output = QString::fromUtf8(p.readAllStandardOutput());
    for (const QString &line : output.split('\n')) {
        if (!line.isEmpty()) appendLog("  " + line);
    }
    return p.exitCode();
}

bool InstallerState::runReproHardwareProbe(const QString &outputPath) {
    // `repro hardware probe --output <path> --regenerate` writes the
    // probed hardware.nim. The wizard later overlays the disko block on
    // top by composing the rendered text directly.
    if (dryRunDestructive()) {
        appendLog(QString("[dry-run] would probe hardware into %1")
                  .arg(outputPath));
        return true;
    }
    QStringList args = {"hardware", "probe", "--output", outputPath,
                        "--regenerate"};
    return runReproSubcommand(args) == 0;
}

bool InstallerState::runReproDiskApply() {
    if (dryRunDestructive()) {
        appendLog("[dry-run] would shell out to `repro disk apply "
                  "--confirm`");
        return true;
    }
    // The wizard writes the disko block to a temp file, then runs
    // `repro disk apply <tmp> --confirm`. The temp file lives under
    // /tmp/repro-installer-<pid>/ + is cleaned up by the OS reboot.
    const QString tmpDir = QString("/tmp/repro-installer-%1")
        .arg(QCoreApplication::applicationPid());
    QDir().mkpath(tmpDir);
    // M9.R.24.2 -- write the JSON form so `repro disk apply` skips
    // the `nim r` compile step (the live ISO doesn't bundle Nim).
    const QString diskoPath = tmpDir + "/disko.json";
    writeFileAtomic(diskoPath, renderDiskoJson());
    QStringList args = {"disk", "apply", diskoPath, "--confirm"};
    if (!m_targetDevice.isEmpty()) {
        args << "--device" << m_targetDevice;
    }
    return runReproSubcommand(args, 600000) == 0;
}

bool InstallerState::runReproDiskMount(const QString &mountPoint) {
    if (dryRunDestructive()) {
        appendLog(QString("[dry-run] would mount disko layout at %1")
                  .arg(mountPoint));
        return true;
    }
    const QString tmpDir = QString("/tmp/repro-installer-%1")
        .arg(QCoreApplication::applicationPid());
    const QString diskoPath = tmpDir + "/disko.json";
    if (!QFileInfo::exists(diskoPath)) {
        writeFileAtomic(diskoPath, renderDiskoJson());
    }
    QStringList args = {"disk", "mount", diskoPath, "--target", mountPoint,
                        "--confirm"};
    return runReproSubcommand(args) == 0;
}

bool InstallerState::runReproDiskUnmount(const QString &mountPoint) {
    if (dryRunDestructive()) {
        appendLog(QString("[dry-run] would unmount %1").arg(mountPoint));
        return true;
    }
    const QString tmpDir = QString("/tmp/repro-installer-%1")
        .arg(QCoreApplication::applicationPid());
    const QString diskoPath = tmpDir + "/disko.json";
    QStringList args = {"disk", "unmount", diskoPath, "--target",
                        mountPoint};
    return runReproSubcommand(args) == 0;
}

bool InstallerState::runReproSystemApply(const QString &target) {
    if (dryRunDestructive()) {
        appendLog(QString("[dry-run] would run `repro infra install-root "
                          "--target %1 --device %2`")
                  .arg(target,
                       m_targetDevice.isEmpty() ? QStringLiteral("/dev/vda")
                                                : m_targetDevice));
        return true;
    }
    // M9.R.41: install-time root-mirror.  The previous
    // ``runReproSystemApply`` path called ``repro infra apply
    // --target`` which the dispatcher never accepted (apply is a
    // system-profile reconciliation, not a root-mirror); the
    // ``runMinimalBootstrap`` fallback only copied kernel + initrd +
    // GRUB and left the rest of /mnt empty.  ``repro infra
    // install-root`` is the install-time analogue: rsync -aHAX the
    // live root onto /mnt, generate fstab from the disko spec Phase
    // 4 wrote to <target>/etc/repro/hardware.nim, then install GRUB
    // + write the target-side grub.cfg.  See M9.R.41.1 commit body.
    const QString grubDevice = m_targetDevice.isEmpty()
        ? QStringLiteral("/dev/vda") : m_targetDevice;
    const QString hn = m_hostname.isEmpty()
        ? QStringLiteral("reproos-vm") : m_hostname;
    // M9.R.41: point install-root at the JSON form of the disko spec
    // the Phase 2 disk-apply step already wrote to /tmp/repro-
    // installer-<pid>/disko.json (via writeFileAtomic +
    // renderDiskoJson).  The Phase 4 /mnt/etc/repro/hardware.nim
    // file is a Nim SOURCE file; loading it via `loadDiskoFromSource`
    // requires ``nim r`` which is NOT bundled on the live ISO (the
    // M9.R.24.2 commit body documented this), so we pass --disko
    // explicitly at the JSON path.
    const QString tmpDir = QString("/tmp/repro-installer-%1")
        .arg(QCoreApplication::applicationPid());
    const QString diskoJson = tmpDir + "/disko.json";
    if (!QFileInfo::exists(diskoJson)) {
        writeFileAtomic(diskoJson, renderDiskoJson());
    }
    QStringList args = {"infra", "install-root",
                        "--target", target,
                        "--source", "/",
                        "--device", grubDevice,
                        "--hostname", hn,
                        "--disko", diskoJson};
    // M9.R.44b: cap bumped from 30 min -> 3 hr.  The original 30 min
    // was sized for an SSD host with KVM passthrough; on the eli-wsl
    // host (Windows -> WSL2 -> QEMU triple-virt, no KVM) Phase 5 rsync
    // runs at ~0.8 MB/s and the from-source live root closure is ~3 GB
    // by M9.R.44, putting Phase 5 wall at 60-90 min.  The 30 min cap
    // killed Phase 5 mid-rsync in the M9.R.42/M9.R.43/M9.R.44b runs;
    // installer reported Phase 5 FAILED while the orphaned rsync child
    // continued silently in the background for another hour.  3 hr
    // covers the slow path with headroom and is still finite enough to
    // surface a genuine wedge.
    return runReproSubcommand(args, 10800000) == 0;
}

bool InstallerState::writeFileAtomic(const QString &path,
                                     const QString &text,
                                     QString *error) {
    const QFileInfo fi(path);
    if (!QDir().mkpath(fi.absolutePath())) {
        const QString message = "cannot create directory: " + fi.absolutePath();
        if (error)
            *error = message;
        appendLog(message);
        return false;
    }
    QSaveFile f(path);
    if (!f.open(QIODevice::WriteOnly | QIODevice::Truncate)) {
        const QString message = QString("write %1 failed: %2")
            .arg(path, f.errorString());
        if (error)
            *error = message;
        appendLog(message);
        return false;
    }
    const QByteArray bytes = text.toUtf8();
    if (f.write(bytes) != bytes.size()) {
        const QString message = QString("write %1 failed: %2")
            .arg(path, f.errorString());
        if (error)
            *error = message;
        appendLog(message);
        f.cancelWriting();
        return false;
    }
    if (!f.commit()) {
        const QString message = QString("commit %1 failed: %2")
            .arg(path, f.errorString());
        if (error)
            *error = message;
        appendLog(message);
        return false;
    }
    appendLog(QString("wrote %1 (%2 bytes)").arg(path)
              .arg(bytes.size()));
    return true;
}

// M9.R.41: ``runMinimalBootstrap`` is DELETED.  The previous M9.R.24
// stub fell through to a kernel+initrd+GRUB-only path when ``repro
// infra apply --target`` failed (which it always did — the subcommand
// never accepted --target).  ``repro infra install-root`` is the real
// implementation; on failure the installer now aborts with an explicit
// error rather than silently producing an unbootable disk.

void InstallerState::install() {
    if (m_installRunning) {
        appendLog("install() called while already running -- ignored");
        return;
    }
    setInstallRunning(true);
    m_installLog.clear();
    emit installLogChanged();
    setInstallProgress(0.0);
    setInstallStatus("Starting install");

    const QString workDirectory = QString("/tmp/repro-installer-%1")
        .arg(QCoreApplication::applicationPid());
    QString artifactError;
    if (!writeConfigurationArtifacts(workDirectory + "/configuration",
                                     &artifactError)) {
        appendLog("configuration generation failed: " + artifactError);
        setInstallRunning(false);
        emit installFailed("configuration generation failed");
        return;
    }

    const QString target = QStringLiteral("/mnt");
    const QString sysNimPath = target + "/etc/repro/system.nim";
    const QString hwNimPath = target + "/etc/repro/hardware.nim";

    appendLog("Phase 1: probing hardware...");
    setInstallStatus("Probing target hardware");
    setInstallProgress(0.1);
    const QString probeOutput = QString("/tmp/repro-installer-%1/probed-hardware.nim")
        .arg(QCoreApplication::applicationPid());
    if (!runReproHardwareProbe(probeOutput)) {
        appendLog("hardware probe failed");
        setInstallRunning(false);
        emit installFailed("hardware probe failed");
        return;
    }

    appendLog("Phase 2: applying disk layout...");
    setInstallStatus("Applying disk layout");
    setInstallProgress(0.3);
    if (!runReproDiskApply()) {
        appendLog("disk apply failed");
        setInstallRunning(false);
        emit installFailed("disk apply failed");
        return;
    }

    appendLog("Phase 3: mounting target rootfs at " + target);
    setInstallStatus("Mounting target");
    setInstallProgress(0.45);
    if (!runReproDiskMount(target)) {
        appendLog("disk mount failed");
        setInstallRunning(false);
        emit installFailed("disk mount failed");
        return;
    }

    appendLog("Phase 4: writing durable ReproOS configuration artifacts");
    setInstallStatus("Writing system configuration");
    setInstallProgress(0.55);
    if (!dryRunDestructive()) {
        if (!writeConfigurationArtifacts(target + "/etc/repro",
                                         &artifactError)) {
            appendLog("configuration write failed: " + artifactError);
            setInstallRunning(false);
            emit installFailed("configuration write failed");
            return;
        }
    } else {
        appendLog(QString("[dry-run] would write %1").arg(sysNimPath));
        appendLog(QString("[dry-run] would write %1").arg(hwNimPath));
    }

    appendLog("Phase 5: applying system profile...");
    setInstallStatus("Applying system profile");
    setInstallProgress(0.7);
    if (!runReproSystemApply(target)) {
        // M9.R.41: ``repro infra install-root`` failed.  This is now
        // a hard error — the M9.R.24 stub's "minimal bootstrap"
        // fallback intentionally left the installed disk without a
        // real rootfs, blocking G3 (boot installed) + G4 (DE smoke).
        // The campaign close-out makes Phase 5 the SOURCE OF TRUTH
        // for the installed system's contents; a failure here means
        // the install is broken and the user must investigate, not
        // silently proceed with a half-formed system.
        appendLog("Phase 5 FAILED: `repro infra install-root` did "
                  "not complete; aborting install (the previous "
                  "M9.R.24 minimal-bootstrap fallback is removed in "
                  "M9.R.41 — a failed install must surface, not "
                  "silently produce an unbootable disk).");
        setInstallRunning(false);
        emit installFailed("system root-mirror failed");
        return;
    }

    appendLog("Phase 6: unmounting target...");
    setInstallStatus("Unmounting");
    setInstallProgress(0.95);
    runReproDiskUnmount(target);

    setInstallProgress(1.0);
    setInstallStatus("Install complete");
    appendLog("install complete");
    setInstallRunning(false);
    emit installComplete();
}

// ---------------------------------------------------------------------
// M9.R.23.5 -- automated config loader. Reads a minimal key=value TOML
// (no nested tables -- this is the smoke-harness path) + drives the
// install() sequence directly.
// ---------------------------------------------------------------------

int InstallerState::runAutomatedConfig(const QString &configPath) {
    QString configError;
    if (!loadAutoConfig(configPath, &configError)) {
        appendLog("automated configuration rejected: " + configError);
        return 1;
    }
    // Track failure via a one-shot signal hook so the return code
    // reflects what actually happened. install() runs synchronously
    // because every helper uses QProcess::waitForFinished.
    bool failed = false;
    QString failureReason;
    auto conn = connect(this, &InstallerState::installFailed, this,
        [&](const QString &reason) {
            failed = true;
            failureReason = reason;
        });
    install();
    disconnect(conn);
    if (failed) {
        QTextStream(stderr) << "install failed: " << failureReason << '\n';
        return 1;
    }
    if (m_installProgress < 1.0) {
        QTextStream(stderr) << "install incomplete (progress=" <<
            m_installProgress << ")\n";
        return 1;
    }
    return 0;
}
