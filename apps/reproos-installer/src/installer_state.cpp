void InstallerState::toggleActivity(const QString &name) {
    if (m_activeActivities.contains(name)) {
        m_activeActivities.removeAll(name);
    } else {
        m_activeActivities.append(name);
        m_activeActivities.sort();
    }
    emit activeActivitiesChanged();
}

bool InstallerState::hasActivity(const QString &name) const {
    return m_activeActivities.contains(name);
}

// Maps PRD Sec 3.1 desktop choice to the activity-shape `dkPlasma` /
// `dkGnome` / `dkSway` / `dkHyprland` variant kinds the
// ReproOS-Configuration-Architecture document defines.
static QString desktopKindToVariant(const QString &kind) {
    if (kind == "plasma") return "dkPlasma";
    if (kind == "gnome") return "dkGnome";
    if (kind == "sway") return "dkSway";
    if (kind == "hyprland") return "dkHyprland";
    return "dkPlasma";
}

QString InstallerState::renderSystemNim() const {
    // Render the user-facing system.nim per PRD Sec 3.3. The format is
    // pinned by ReproOS-Configuration-Architecture; the
    // `import repro_profile` + `system "<name>":` header is canonical.
    QString out;
    QTextStream s(&out);
    s << "# /etc/repro/system.nim --- generated by the ReproOS installer\n";
    s << "import repro_profile\n\n";
    s << "system \"" << m_hostname << "\":\n";
    s << "  imports:\n";
    s << "    \"./hardware.nim\"\n";
    for (const QString &act : m_activeActivities) {
        s << "    \"modules/activities/" << act << ".nim\"\n";
    }
    s << "    \"modules/de/" << m_desktopKind << ".nim\"\n";
    s << "    \"modules/networking/networkmanager.nim\"\n\n";
    s << "  config:\n";
    s << "    hostname: string = \"" << m_hostname << "\"\n";
    s << "    timezone: string = \"" << m_timezone << "\"\n";
    s << "    locale: string = \"" << m_locale << "\"\n";
    s << "    keymap: string = \"" << m_keymap << "\"\n";
    s << "    activeAtBoot: DesktopKind = " << desktopKindToVariant(m_desktopKind) << "\n";
    s << "    defaultUser: string = \"" << m_username << "\"\n\n";
    s << "  users:\n";
    s << "    \"" << m_username << "\":\n";
    s << "      fullName: \"" << m_fullName << "\"\n";
    s << "      groups: @[";
    s << "\"audio\", \"video\", \"networkmanager\"";
    if (m_isAdmin) s << ", \"wheel\"";
    s << "]\n";
    s << "      homeIntent: import \"./home.nim\"\n";
    return out;
}

static QString tomlQuoted(const QString &value) {
    QString escaped = value;
    escaped.replace('\\', "\\\\");
    escaped.replace('"', "\\\"");
    escaped.replace('\n', "\\n");
    return QStringLiteral("\"") + escaped + QStringLiteral("\"");
}

static QString tomlStringArray(const QStringList &values) {
    QStringList quoted;
    for (const QString &value : values)
        quoted.append(tomlQuoted(value));
    return QStringLiteral("[") + quoted.join(", ") + QStringLiteral("]");
}

QString InstallerState::ensurePasswordHash(QString *error) {
    if (!m_passwordHash.isEmpty())
        return m_passwordHash;
    if (m_password.isEmpty()) {
        if (error)
            *error = "a password or password_hash is required";
        return {};
    }

    static const char saltAlphabet[] =
        "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789./";
    QString salt;
    for (int i = 0; i < 16; ++i) {
        const auto index = QRandomGenerator::system()->bounded(
            static_cast<quint32>(sizeof(saltAlphabet) - 1));
        salt.append(saltAlphabet[index]);
    }

    const QString program = qEnvironmentVariable(
        "REPRO_OPENSSL_BINARY", "openssl");
    QProcess process;
    process.setProcessChannelMode(QProcess::MergedChannels);
    process.start(program, {"passwd", "-6", "-salt", salt, "-stdin"});
    if (!process.waitForStarted(5000)) {
        if (error)
            *error = QString("cannot start %1: %2")
                .arg(program, process.errorString());
        return {};
    }
    process.write(m_password.toUtf8());
    process.write("\n");
    process.closeWriteChannel();
    if (!process.waitForFinished(30000) || process.exitCode() != 0) {
        if (error)
            *error = QString("password hashing failed: %1")
                .arg(QString::fromUtf8(process.readAll()).trimmed());
        return {};
    }
    m_passwordHash = QString::fromUtf8(process.readAll()).trimmed();
    if (!m_passwordHash.startsWith("$6$")) {
        if (error)
            *error = "password hashing returned an unexpected format";
        m_passwordHash.clear();
    }
    return m_passwordHash;
}

QString InstallerState::renderAutoConfigToml() {
    QString hash;
    if (m_schemaVersion == 1) {
        QString hashError;
        hash = ensurePasswordHash(&hashError);
        if (hash.isEmpty())
            return {};
    }

    QString out;
    QTextStream s(&out);
    s << "# ReproOS unattended installation configuration\n";
    s << "schema_version = " << m_schemaVersion << "\n";
    s << "hostname = " << tomlQuoted(m_hostname) << "\n\n";
    s << "[regional]\n";
    s << "locale = " << tomlQuoted(m_locale) << "\n";
    s << "timezone = " << tomlQuoted(m_timezone) << "\n";
    s << "keymap = " << tomlQuoted(m_keymap) << "\n\n";
    s << "[user]\n";
    s << "name = " << tomlQuoted(m_username) << "\n";
    s << "full_name = " << tomlQuoted(m_fullName) << "\n";
    if (m_schemaVersion == 1)
        s << "password_hash = " << tomlQuoted(hash) << "\n";
    else
        s << "locked = true\n";
    QStringList groups = {"audio", "video", "networkmanager"};
    if (m_isAdmin)
        groups.prepend("wheel");
    s << "groups = " << tomlStringArray(groups) << "\n";
    s << "shell = " << tomlQuoted(m_userShell) << "\n\n";
    if (m_schemaVersion == 2) {
        s << "[sudo]\n";
        s << "policy = " << tomlQuoted(m_sudoPolicy) << "\n";
        s << "users = " << tomlStringArray(m_sudoUsers) << "\n\n";
    }
    s << "[disk]\n";
    s << "size_gb = " << m_diskSizeGb << "\n\n";
    s << "[disk.layout]\n";
    s << "type = \"uefi-ext4\"\n";
    s << "esp_size_mib = " << m_espSizeMib << "\n\n";
    s << "[de]\n";
    s << "default = " << tomlQuoted(m_desktopKind) << "\n\n";
    s << "[network]\n";
    s << "ipv4 = " << tomlQuoted(m_networkIpv4) << "\n\n";
    if (m_schemaVersion == 2) {
        s << "[ssh]\n";
        s << "enabled = " << (m_sshEnabled ? "true" : "false") << "\n";
        s << "permit_root_login = "
          << (m_sshPermitRootLogin ? "true" : "false") << "\n";
        s << "password_authentication = "
          << (m_sshPasswordAuthentication ? "true" : "false") << "\n";
        s << "authorized_keys_source = "
          << tomlQuoted(m_sshAuthorizedKeysSource) << "\n\n";
        s << "[firewall]\n";
        s << "default_policy = " << tomlQuoted(m_firewallDefaultPolicy) << "\n";
        s << "allowed_tcp_ports = [" << m_firewallAllowedTcpPorts.join(", ")
          << "]\n";
        s << "ssh_source_cidrs = "
          << tomlStringArray(m_firewallSshSourceCidrs) << "\n\n";
        s << "[first_boot]\n";
        s << "enrollment = " << tomlQuoted(m_firstBootEnrollment) << "\n";
        s << "enrollment_label = "
          << tomlQuoted(m_firstBootEnrollmentLabel) << "\n\n";
    }
    s << "[activities]\n";
    s << "enabled = " << tomlStringArray(m_activeActivities) << "\n\n";
    s << "[install]\n";
    s << "target_device = " << tomlQuoted(
        m_targetDevice.isEmpty() ? QStringLiteral("/dev/vda")
                                 : m_targetDevice) << "\n";
    return out;
}

